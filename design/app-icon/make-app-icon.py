#!/usr/bin/env python3
"""Builds every Crow HR app icon from one layout: the Crow Tech crow standing on a kuning "HR" card.

Writes, relative to the repo root:
  design/app-icon/crow-hr-icon.svg                                   master artwork (1024 square)
  apps/android/app/src/main/res/drawable/ic_launcher_foreground.xml  adaptive icon, colour layer
  apps/android/app/src/main/res/drawable/ic_launcher_monochrome.xml  adaptive icon, themed layer
and, through design/app-icon/render.cjs (Chromium via the repo's Playwright):
  apps/ios/CrowHR/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png  (opaque RGB)
  apps/android/store/icon-512.png                                    Play listing icon (opaque RGB)
  design/app-icon/crow-hr-icon-1024.png                              master raster

Usage (repo root): python3 design/app-icon/make-app-icon.py   (needs fontTools, Pillow, node)
The "HR" glyphs are Azeret Mono Bold (SIL OFL 1.1, @fontsource/azeret-mono) converted to paths,
so no font ships with the icon.
"""
import glob
import io
import re
import subprocess
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "design/app-icon"

IVORY = "#FBF6EA"  # warm ivory, the background shared with Crow Tech's other app icons
INK = "#0A0A0A"  # Crow Tech ink
KUNING = "#FED56C"  # kuning-200, the Crow HR accent

# Layout in a 1000-unit square.
CARD = dict(x=172, y=596, w=636, h=262, r=26, stroke=20, shadow=24)
TEXT = dict(s="HR", cap=150)
CROW = dict(x=262, feet=586, w=505)
# The traced crow's bounds in its own 2000 px space (see crow-tech-crow.svg).
CX0, CY1, CX1 = 164, 1768, 1811
# Adaptive icons: everything must sit inside the 66 dp safe circle of the 108 dp canvas.
ANDROID_SCALE = 0.62

crow_d = re.search(r'd="([^"]*)"', (HERE / "crow-tech-crow.svg").read_text(), re.S).group(1)


def font_file() -> TTFont:
    hits = glob.glob(str(ROOT / "node_modules/**/@fontsource/azeret-mono/files/azeret-mono-latin-700-normal.woff2"), recursive=True, include_hidden=True)
    if not hits:
        raise SystemExit("Azeret Mono 700 not found: run `bun install` first.")
    font = TTFont(hits[0])
    font.flavor = None
    buf = io.BytesIO()
    font.save(buf)
    buf.seek(0)
    return TTFont(buf)


def text_path() -> str:
    font = font_file()
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    s = TEXT["cap"] / font["OS/2"].sCapHeight
    names = [cmap[ord(ch)] for ch in TEXT["s"]]
    x = CARD["x"] + CARD["w"] / 2 - sum(glyphs[n].width for n in names) * s / 2
    baseline = CARD["y"] + CARD["h"] / 2 + TEXT["cap"] / 2
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    for n in names:
        glyphs[n].draw(TransformPen(pen, (s, 0, 0, -s, x, baseline)))
        x += glyphs[n].width * s
    return pen.getCommands()


def rounded_rect(x, y, w, h, r) -> str:
    return (
        f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
        f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
        f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z"
    )


def crow_transform():
    s = CROW["w"] / (CX1 - CX0)
    return CROW["x"] - CX0 * s, CROW["feet"] - CY1 * s, s


HR = text_path()
c = CARD
CARD_D = rounded_rect(c["x"], c["y"], c["w"], c["h"], c["r"])
SHADOW_D = rounded_rect(c["x"] + c["shadow"], c["y"] + c["shadow"], c["w"], c["h"], c["r"])
TX, TY, TS = crow_transform()


def master_svg(size=1024) -> str:
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 1000 1000">
<title>Crow HR</title>
<!-- Crow HR app icon. Generated by design/app-icon/make-app-icon.py; edit that, not this. -->
<rect width="1000" height="1000" fill="{IVORY}"/>
<path fill="{INK}" d="{SHADOW_D}"/>
<path fill="{KUNING}" stroke="{INK}" stroke-width="{c["stroke"]}" d="{CARD_D}"/>
<path fill="{INK}" d="{HR}"/>
<g transform="translate({TX:.3f},{TY:.3f}) scale({TS:.6f})"><g transform="translate(0,2000) scale(0.1,-0.1)"><path fill="{INK}" d="{crow_d}"/></g></g>
</svg>
"""


def vector(monochrome: bool) -> str:
    k = 108 / 1000 * ANDROID_SCALE
    off = 108 * (1 - ANDROID_SCALE) / 2
    if monochrome:
        card = f'        <path android:pathData="{CARD_D}" android:strokeColor="#FF000000" android:strokeWidth="{c["stroke"]}" android:fillColor="#00000000" />'
        fill = "#FF000000"
        note = "Themed (monochrome) layer: the system tints it, so only shape matters."
    else:
        card = (
            f'        <path android:pathData="{SHADOW_D}" android:fillColor="{INK}" />\n'
            f'        <path android:pathData="{CARD_D}" android:fillColor="{KUNING}" android:strokeColor="{INK}" android:strokeWidth="{c["stroke"]}" />'
        )
        fill = INK
        note = "Colour layer, on @color/launcher_background (ivory)."
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!--
  Crow HR app icon: the Crow Tech crow standing on a kuning "HR" card. {note}
  Generated by design/app-icon/make-app-icon.py; edit that, not this file.
  Content is scaled to {ANDROID_SCALE} so it stays inside the adaptive icon's 66 dp safe circle.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="{off:.3f}"
        android:translateY="{off:.3f}"
        android:scaleX="{k:.6f}"
        android:scaleY="{k:.6f}">
{card}
        <path android:pathData="{HR}" android:fillColor="{fill}" />
        <group
            android:translateX="{TX:.3f}"
            android:translateY="{TY:.3f}"
            android:scaleX="{TS:.6f}"
            android:scaleY="{TS:.6f}">
            <group android:translateY="2000" android:scaleX="0.1" android:scaleY="-0.1">
                <path android:pathData="{crow_d}" android:fillColor="{fill}" />
            </group>
        </group>
    </group>
</vector>
"""


def render(svg_path: Path, png_path: Path, size: int) -> None:
    png_path.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["node", str(HERE / "render.cjs"), str(svg_path), str(png_path), str(size)], check=True, cwd=ROOT)
    Image.open(png_path).convert("RGB").save(png_path, "PNG", optimize=True)  # stores reject alpha


def main() -> None:
    svg = HERE / "crow-hr-icon.svg"
    svg.write_text(master_svg())
    res = ROOT / "apps/android/app/src/main/res/drawable"
    (res / "ic_launcher_foreground.xml").write_text(vector(False))
    (res / "ic_launcher_monochrome.xml").write_text(vector(True))
    render(svg, HERE / "crow-hr-icon-1024.png", 1024)
    render(svg, ROOT / "apps/ios/CrowHR/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png", 1024)
    render(svg, ROOT / "apps/android/store/icon-512.png", 512)
    print("Crow HR icons written.")


if __name__ == "__main__":
    main()
