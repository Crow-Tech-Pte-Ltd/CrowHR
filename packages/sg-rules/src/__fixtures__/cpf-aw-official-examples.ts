/**
 * CPF Board, "Examples for computation of Additional Wage (AW) Ceiling" (2026 figures),
 * all 16 worked examples, transcribed month by month from the official PDF:
 * https://www.cpf.gov.sg/service/sfc/servlet.shepherd/document/download/069IW00000jyH92YAE
 *
 * Each row: [month, owPaid, owSubject, owEmployer, owEmployee, awPaid, awSubject, awEmployer, awEmployee]
 * in integer cents for 2026. "AW subject" in CPF's table includes AW of earlier months re-subjected
 * in that month after the AW ceiling was recomputed (shortfall), so the engine's current-month AW
 * subject plus its prior-AW shortfall must equal it. Months with no wages are omitted.
 * Birth dates are chosen to match the narrative ("turned 55 in June 2026" etc.); day of month is
 * irrelevant to the CPF age rule.
 */

