/**
 * Regenerates src/pdf/fonts.generated.ts: the latin subsets of Azeret Mono and Ubuntu from
 * @fontsource (WOFF 1.0), converted to plain TrueType and embedded as base64 so the PDF renderer
 * needs no file access or network (runtime-agnostic core; the browser demo runs it too).
 *
 *   node packages/core/scripts/pdf-fonts.ts
 *
 * Licences: Azeret Mono is SIL OFL 1.1, Ubuntu is the Ubuntu Font Licence 1.0; both texts are copied
 * to src/pdf/FONT-LICENSES.txt next to the generated module.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { inflateSync } from "node:zlib";

const require = createRequire(new URL("../../ui/package.json", import.meta.url));
const azeret = dirname(require.resolve("@fontsource/azeret-mono/package.json"));
const ubuntu = dirname(require.resolve("@fontsource/ubuntu/package.json"));

const FONTS = [
  { name: "AzeretMono-Regular", file: join(azeret, "files/azeret-mono-latin-400-normal.woff") },
  { name: "AzeretMono-SemiBold", file: join(azeret, "files/azeret-mono-latin-600-normal.woff") },
  { name: "Ubuntu-Regular", file: join(ubuntu, "files/ubuntu-latin-400-normal.woff") },
  { name: "Ubuntu-Medium", file: join(ubuntu, "files/ubuntu-latin-500-normal.woff") },
] as const;

/** WOFF 1.0 → sfnt (https://www.w3.org/TR/WOFF/ §4–5). */
export function woffToSfnt(woff: Uint8Array): Uint8Array {
  const v = new DataView(woff.buffer, woff.byteOffset, woff.byteLength);
  if (v.getUint32(0) !== 0x774f4646) throw new Error("not a WOFF 1.0 file");
  const flavor = v.getUint32(4);
  const numTables = v.getUint16(12);
  const tables: { tag: number; checksum: number; data: Uint8Array }[] = [];
  for (let i = 0; i < numTables; i++) {
    const o = 44 + i * 20;
    const tag = v.getUint32(o);
    const offset = v.getUint32(o + 4);
    const compLength = v.getUint32(o + 8);
    const origLength = v.getUint32(o + 12);
    const checksum = v.getUint32(o + 16);
    const raw = woff.subarray(offset, offset + compLength);
    const data = compLength < origLength ? new Uint8Array(inflateSync(raw)) : raw;
    if (data.length !== origLength) throw new Error("bad WOFF table length");
    tables.push({ tag, checksum, data });
  }
  tables.sort((a, b) => a.tag - b.tag);
  const pad = (n: number) => (n + 3) & ~3;
  let size = 12 + numTables * 16;
  for (const t of tables) size += pad(t.data.length);
  const out = new Uint8Array(size);
  const w = new DataView(out.buffer);
  let pow = 1;
  let log = 0;
  while (pow * 2 <= numTables) {
    pow *= 2;
    log++;
  }
  w.setUint32(0, flavor);
  w.setUint16(4, numTables);
  w.setUint16(6, pow * 16);
  w.setUint16(8, log);
  w.setUint16(10, numTables * 16 - pow * 16);
  let offset = 12 + numTables * 16;
  tables.forEach((t, i) => {
    const r = 12 + i * 16;
    w.setUint32(r, t.tag);
    w.setUint32(r + 4, t.checksum);
    w.setUint32(r + 8, offset);
    w.setUint32(r + 12, t.data.length);
    out.set(t.data, offset);
    offset += pad(t.data.length);
  });
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const lines = [
    "// GENERATED by packages/core/scripts/pdf-fonts.ts: do not edit. Latin subsets from @fontsource,",
    "// WOFF converted to TrueType. Azeret Mono: SIL OFL 1.1. Ubuntu: Ubuntu Font Licence 1.0.",
    "// Licence texts: ./FONT-LICENSES.txt.",
    "",
  ];
  for (const f of FONTS) {
    const ttf = woffToSfnt(new Uint8Array(readFileSync(f.file)));
    lines.push(`export const ${f.name.replace("-", "_")} = "${Buffer.from(ttf).toString("base64")}";`, "");
  }
  const here = new URL("../src/pdf/", import.meta.url);
  writeFileSync(new URL("fonts.generated.ts", here), lines.join("\n"));
  writeFileSync(
    new URL("FONT-LICENSES.txt", here),
    [
      "Fonts embedded in Crow HR PDFs (src/pdf/fonts.generated.ts)",
      "",
      "=== Azeret Mono (@fontsource/azeret-mono) ===",
      readFileSync(join(azeret, "LICENSE"), "utf8"),
      "",
      "=== Ubuntu (@fontsource/ubuntu) ===",
      readFileSync(join(ubuntu, "LICENSE"), "utf8"),
    ].join("\n"),
  );
  console.error(`Wrote ${FONTS.length} fonts.`);
}
